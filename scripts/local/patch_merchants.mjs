#!/usr/bin/env node
// Give the local stack a place to sell.
//
// The pinned `design/maps.js` ships no `merchants` arrays at all, and `socket.on("sell")`
// (node/server.js) refuses every sale unless a map merchant is within `B.sell_dist` (400):
//
//   (G.maps[player.map].merchants || []).forEach(function (m) {
//     if (simple_distance(player, m) < B.sell_dist) can_reach = m;
//   });
//   if (!can_reach) return fail_response("distance");
//
// So on a fresh clone nothing can be sold anywhere - not by a bot, not through the UI. This script
// appends one guarded block to the cloned map data, at the position of the real `standmerchant`
// NPC on main (-193,680), which sits just south of the goo field the fixtures farm.
//
// It edits the clone under reference/local/, which is git-ignored and fetched at container start, so
// nothing is redistributed. Idempotent: the marker comment is the guard.
//
//   AL_TEST_MERCHANT=off        do not patch (leave the stack exactly as upstream ships it)
//   AL_TEST_MERCHANT=main:-100,900   patch a different map/position
//
// Local use:  node scripts/local/patch_merchants.mjs [--file <maps.js>] [--spec <map:x,y>]

import fs from "node:fs/promises";
import path from "node:path";
import { GAME } from "./apply_config.mjs";

export const MARKER = "/* local test merchant (generated by scripts/local/patch_merchants.mjs) */";
export const DEFAULT_SPEC = "main:-193,680";

/** Parse `map:x,y`; `off`/`none`/`` mean "do not patch". Returns null for off. */
export function parseSpec(value = DEFAULT_SPEC) {
	const text = String(value ?? "").trim();
	if (!text || /^(off|none|no|0|false)$/i.test(text)) return null;
	const match = /^([A-Za-z0-9_]+)\s*:\s*(-?[0-9]+(?:\.[0-9]+)?)\s*,\s*(-?[0-9]+(?:\.[0-9]+)?)$/.exec(text);
	if (!match) throw new Error("AL_TEST_MERCHANT must be 'off' or 'map:x,y', got " + JSON.stringify(text));
	const [, map, x, y] = match;
	return { map, x: Number(x), y: Number(y), id: "standmerchant" };
}

/** The block appended to design/maps.js. Pure so it can be asserted in tests. */
export function merchantBlock(spec) {
	if (!spec) return "";
	const x = Number.isInteger(spec.x) ? String(spec.x) : String(spec.x);
	const y = Number.isInteger(spec.y) ? String(spec.y) : String(spec.y);
	return [
		"",
		MARKER,
		"(function () {",
		'\tif (!maps["' + spec.map + '"]) return;',
		'\tmaps["' + spec.map + '"].merchants = [{ id: "' + spec.id + '", x: ' + x + ", y: " + y + " }];",
		"})();",
		"",
	].join("\n");
}

/** True when the file already carries the patch (any spec: one block is enough). */
export function isPatched(source) {
	return String(source).includes(MARKER);
}

/**
 * Apply the patch to a source string.
 * Returns { source, changed }; changed is false when the marker is already there.
 */
export function patchSource(source, spec) {
	if (!spec) return { source, changed: false };
	if (isPatched(source)) return { source, changed: false };
	const body = String(source);
	const separator = body.endsWith("\n") ? "" : "\n";
	return { source: body + separator + merchantBlock(spec), changed: true };
}

function flag(args, name, fallback) {
	const index = args.indexOf("--" + name);
	return index >= 0 && args[index + 1] && !args[index + 1].startsWith("--") ? args[index + 1] : fallback;
}

export async function main(argv = process.argv.slice(2)) {
	const file = path.resolve(flag(argv, "file", path.join(GAME, "design/maps.js")));
	const spec = parseSpec(flag(argv, "spec", process.env.AL_TEST_MERCHANT || DEFAULT_SPEC));
	if (!spec) {
		console.log("[merchants] AL_TEST_MERCHANT=off, the stack keeps its upstream (merchant-less) maps");
		return { changed: false, skipped: true };
	}
	let source;
	try {
		source = await fs.readFile(file, "utf8");
	} catch {
		console.log("[merchants] " + file + " is not there yet (clone missing), nothing to patch");
		return { changed: false, skipped: true };
	}
	const result = patchSource(source, spec);
	if (!result.changed) {
		console.log("[merchants] already patched: " + spec.map + " " + spec.x + "," + spec.y);
		return { changed: false, skipped: false };
	}
	await fs.writeFile(file, result.source);
	console.log("[merchants] added a test merchant on " + spec.map + " at " + spec.x + "," + spec.y + " (" + file + ")");
	return { changed: true, skipped: false };
}

const invokedDirectly = process.argv[1] && import.meta.url === new URL("file://" + path.resolve(process.argv[1])).href;
if (invokedDirectly) {
	main().catch((error) => {
		console.error("[merchants] " + (error && error.message ? error.message : error));
		process.exit(1);
	});
}
