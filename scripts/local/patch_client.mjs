// Inject the ?watch= deep link into the cloned browser client.
//
// Upstream's client parses no query parameters at all, so watching a character is click-only
// (js/game.js observe_character). The local stack is a git-ignored clone, so a small generated block
// appended to js/game.js is enough to make /?watch=<name> work - and appending to a static file means
// no template cache or server restart is involved, one page reload is enough.

import fs from "node:fs/promises";
import path from "node:path";
import { GAME, ROOT } from "./apply_config.mjs";

const TARGET = path.join(GAME, "js/game.js");
const RUNTIME = path.join(ROOT, "scripts/local/local_watch.js");
const MARKER = "/* local watch deep link (generated by scripts/local/patch_client.mjs) */";

export async function patchClient() {
	let source;
	try {
		source = await fs.readFile(TARGET, "utf8");
	} catch {
		return { patched: false, reason: "game clone not fetched" };
	}
	const runtime = await fs.readFile(RUNTIME, "utf8");
	const without = source.includes(MARKER) ? source.slice(0, source.indexOf(MARKER)) : source;
	const next = without.replace(/\s*$/, "") + "\n\n" + MARKER + "\n" + runtime;
	if (next === source) return { patched: false, reason: "already up to date" };
	await fs.writeFile(TARGET, next);
	return { patched: true, reason: source.includes(MARKER) ? "refreshed" : "added" };
}

if (process.argv[1] && process.argv[1].endsWith("patch_client.mjs")) {
	const result = await patchClient();
	console.log("[patch_client] " + (result.reason || "done"));
}
