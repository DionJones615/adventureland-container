#!/usr/bin/env node
// Generate the local stack configuration (idempotent).
//
// The upstream config template is a git repository of its own; this script keeps the template's
// defaults but adds the two things a local install needs and the template lacks:
//
//   * servers.local.msgpack_path - the game server refuses to boot without it
//   * stable development keys - the template regenerates random keys on every require(), so two
//     processes (backend and game server) would disagree about SERVER_MASTER and invalidate
//     each other's sessions
//
// Everything it writes lives under reference/local/, which is git-ignored.

import { createRequire } from "node:module";
import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(HERE, "../..");
export const LOCAL = path.join(ROOT, "reference/local");
export const GAME = path.join(LOCAL, "adventureland");
export const SECRETS = path.join(LOCAL, "secretsandconfig");

const MARKER = "// Generated by scripts/local/apply_config.mjs";
const DEFAULT_API_PORT = 8090;
const DEFAULT_GAME_PORT = 7192;
const DEFAULT_MONGODB_PORT = 27017;
const DEFAULT_DB = "adventureland";

export const dirs = {
	state: path.join(LOCAL, ".state"),
	cache: path.join(LOCAL, ".cache"),
	mongoData: path.join(LOCAL, ".data/mongo"),
	logs: path.join(LOCAL, ".logs"),
	run: path.join(LOCAL, ".run"),
};

export function ports() {
	const int = (value, fallback) => {
		const parsed = Number.parseInt(value ?? "", 10);
		return Number.isFinite(parsed) && parsed > 0 ? parsed : fallback;
	};
	return {
		api: int(process.env.AL_API_PORT, DEFAULT_API_PORT),
		game: int(process.env.AL_GAME_PORT, DEFAULT_GAME_PORT),
		mongo: int(process.env.AL_MONGODB_PORT, DEFAULT_MONGODB_PORT),
	};
}

async function exists(file) {
	try {
		await fs.access(file);
		return true;
	} catch {
		return false;
	}
}

async function readJson(file, fallback) {
	try {
		return JSON.parse(await fs.readFile(file, "utf8"));
	} catch {
		return fallback;
	}
}

/** The committed template options.js, recovered without a network round trip. */
async function gitTemplate() {
	const { execFile } = await import("node:child_process");
	return new Promise((resolve) => {
		execFile("git", ["-C", SECRETS, "show", "HEAD:options.js"], { maxBuffer: 4 * 1024 * 1024 }, (error, stdout) =>
			resolve(error || !stdout ? null : stdout),
		);
	});
}

async function writeIfChanged(file, content) {
	try {
		const current = await fs.readFile(file, "utf8");
		if (current === content) return false;
	} catch {}
	await fs.mkdir(path.dirname(file), { recursive: true });
	await fs.writeFile(file, content);
	return true;
}

/** Stable development keys: generated once, reused by every process and every restart. */
async function stableKeys() {
	const file = path.join(dirs.state, "keys.json");
	const keys = await readJson(file, {});
	const need = ["server_keyword", "sdk_password", "ACCESS_MASTER", "BOT_MASTER", "SERVER_MASTER"];
	const missing = need.filter((name) => typeof keys[name] !== "string" || keys[name].length < 8);
	if (missing.length) {
		const sizes = { server_keyword: 16, sdk_password: 16, ACCESS_MASTER: 20, BOT_MASTER: 20, SERVER_MASTER: 16 };
		for (const name of missing) keys[name] = crypto.randomBytes(sizes[name]).toString("hex");
		await fs.mkdir(dirs.state, { recursive: true });
		await fs.writeFile(file, JSON.stringify(keys, null, 2) + "\n");
	}
	return keys;
}

function keysSource(keys, { mongoPort, db }) {
	return `${MARKER} - local development keys, not secrets to anything real.
// Stable across restarts so the backend and the game server agree with each other.
module.exports = {
	server_keyword: "${keys.server_keyword}",
	mongodb_uri: process.env.AL_MONGODB_URI || "mongodb://127.0.0.1:${mongoPort}/${db}",
	mongodb_name: process.env.AL_MONGODB_NAME || "${db}",
	mongodb_config: {},
	stripe_test_api_key: "",
	stripe_test_pkey: "",
	stripe_api_key: "",
	stripe_pkey: "",
	steam_web_apikey: "",
	steam_publisher_web_apikey: "",
	sdk_password: "${keys.sdk_password}",
	amazon_ses_user: "",
	amazon_ses_key: "",
	ACCESS_MASTER: "${keys.ACCESS_MASTER}",
	BOT_MASTER: "${keys.BOT_MASTER}",
	SERVER_MASTER: "${keys.SERVER_MASTER}",
	discord_token: "",
	apple_token: "",
	steam_key: "",
};
`;
}

function optionsSource() {
	return `${MARKER} - template defaults plus the local overrides this stack needs.
const base = require("./options_base.js");

const apiPort = Number.parseInt(process.env.AL_API_PORT || "", 10) || base.port;
const gamePort = Number.parseInt(process.env.AL_GAME_PORT || "", 10) || base.servers.local.local_port;
const local = Object.assign({}, base.servers.local, {
	msgpack_path: "/socket.io-msgpack/",
	local_port: gamePort,
	address: "localhost:" + gamePort,
});
const servers = Object.assign({}, base.servers, { local });

module.exports = Object.assign({}, base, {
	port: apiPort,
	base_url: process.env.AL_BASE_URL || base.base_url,
	servers,
});
`;
}

/**
 * The cloned repositories live inside this corpus, whose root package.json declares "type": "module".
 * Their own sources are CommonJS and two of the three repos ship no package.json of their own, so
 * without this marker Node would parse them as ESM and the servers would fail to boot.
 */
async function ensureCommonJs() {
	const changed = [];
	for (const dir of [SECRETS, path.join(LOCAL, "common")]) {
		const file = path.join(dir, "package.json");
		if (await writeIfChanged(file, JSON.stringify({ type: "commonjs" }, null, 2) + "\n")) changed.push(path.relative(LOCAL, file));
	}
	return changed;
}

/** Write secretsandconfig/{keys.js,options_base.js,options.js}. Returns changed file names. */
export async function applyConfig({ quiet = false } = {}) {
	const changed = await ensureCommonJs();
	const { mongo, api, game } = ports();
	await fs.mkdir(dirs.state, { recursive: true });

	const keys = await stableKeys();
	if (await writeIfChanged(path.join(SECRETS, "keys.js"), keysSource(keys, { mongoPort: mongo, db: DEFAULT_DB })))
		changed.push("keys.js");

	const optionsFile = path.join(SECRETS, "options.js");
	const baseFile = path.join(SECRETS, "options_base.js");
	if (!(await exists(baseFile))) {
		const current = await fs.readFile(optionsFile, "utf8");
		if (current.startsWith(MARKER)) {
			// options_base.js is missing but options.js is already our generated wrapper: the pristine
			// template has to come back from git, otherwise the generator has nothing to copy.
			const template = await gitTemplate();
			if (!template) {
				throw new Error(
					"reference/local/secretsandconfig is missing the template options.js.\n" +
						"  Fix: git -C reference/local/secretsandconfig checkout -- options.js\n" +
						"  Then re-run npm run local:up.",
				);
			}
			await fs.writeFile(baseFile, template);
			changed.push("options_base.js (restored from git)");
		} else {
			await fs.writeFile(baseFile, current);
			changed.push("options_base.js");
		}
	}
	if (await writeIfChanged(optionsFile, optionsSource())) changed.push("options.js");

	// The template only supports the ports as written; the generated module handles AL_*_PORT.
	// Verify the result is loadable and carries the fields the servers actually read.
	const require = createRequire(path.join(SECRETS, "options.js"));
	for (const file of ["./options.js", "./keys.js"]) {
		delete require.cache[require.resolve(file)];
	}
	const loaded = require("./options.js");
	const loadedKeys = require("./keys.js");
	const problems = [];
	if (!loaded?.servers?.local) problems.push("options.servers.local missing");
	if (loaded?.servers?.local && loaded.servers.local.msgpack_path !== "/socket.io-msgpack/")
		problems.push("servers.local.msgpack_path not set");
	if (loaded?.servers?.local && loaded.servers.local.local_port !== game)
		problems.push("servers.local.local_port is " + loaded.servers.local.local_port + ", expected " + game);
	if (loaded?.port !== api) problems.push("options.port is " + loaded.port + ", expected " + api);
	if (loaded?.Dev !== true) problems.push("options.Dev must be true for local signup");
	if (loaded?.Local !== true) problems.push("options.Local must be true so the game server listens on local_port");
	if (typeof loadedKeys?.mongodb_uri !== "string" || !loadedKeys.mongodb_uri.startsWith("mongodb://127.0.0.1"))
		problems.push("keys.mongodb_uri must point at 127.0.0.1");
	if (loadedKeys?.SERVER_MASTER !== require("./keys.js").SERVER_MASTER) problems.push("keys are not stable");
	if (problems.length) throw new Error("local config is not usable:\n  - " + problems.join("\n  - "));

	// The ?watch= deep link lives in the cloned client, which a refresh restores; re-apply it here so
	// every start has it without a separate step.
	try {
		const { patchClient } = await import("./patch_client.mjs");
		const patch = await patchClient();
		if (patch.patched) changed.push("js/game.js (" + patch.reason + ")");
	} catch (error) {
		if (!quiet) console.warn("[apply_config] client patch skipped: " + error.message);
	}


	if (!quiet) {
		console.log("[apply_config] ports: api=" + api + " game=" + game + " mongo=" + mongo);
		console.log("[apply_config] changed: " + (changed.join(", ") || "nothing"));
	}
	return { changed, ports: ports(), db: DEFAULT_DB };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
	applyConfig().catch((error) => {
		console.error("[apply_config] " + error.message);
		process.exit(1);
	});
}
